"""Zone-offset snapshot and oracle table for the IANA zones in registries/calendars.toml (plan §25.4, bd-029).

The source is CPython's zoneinfo over the system tzdata (its version is read from <tzdir>/+VERSION). fmine-time
shares no code with it. The span is 1970-01-01 to 2100-01-01 UTC: IANA vouches for its data from 1970, and every
instant outside the span is refused, never extrapolated.

Two outputs, both to stdout:

  registry  registries/zones.toml. Rows: one [[zone]] per zone (its offset at the start of the span and the sha256
            of the TZif file read) and one [[transition]] per offset change inside the span, in time order. A
            change is found by sampling the offset every hour and bisecting to the second, so two changes less
            than an hour apart would be missed; the script fails if a found change does not hold at its second.
  oracle    fixtures/fmine-time/zone_oracle_1970_2100.txt, one fact per line. The instants sit around the changes
            found as above; the fact at each comes from datetime arithmetic (fold 0 and 1, per PEP 495), not from
            the change list:
              offset <zone> <utc_s> <offset_minutes>      one second before and at every transition
              local <zone> <local_s> unique <utc_s>       local_s counts seconds of local wall-clock time from
              local <zone> <local_s> gap                  1970-01-01T00:00; four instants around each transition:
              local <zone> <local_s> ambiguous            each edge of the skipped or repeated hour
              cut <site_id> <YYYY-MM-DD> <utc_s>          the site's production-day start (day_start_local_hour)
              cut <site_id> <YYYY-MM-DD> gap|ambiguous    on 15 January and 15 July of every year, and on each
                                                          local date of a transition in the site's zone

Usage:
  python3 -I scripts/oracle/zone_snapshot.py registry > registries/zones.toml
  python3 -I scripts/oracle/zone_snapshot.py oracle > fixtures/fmine-time/zone_oracle_1970_2100.txt
"""

import datetime
import hashlib
import pathlib
import sys
import tomllib
import zoneinfo

ROOT = pathlib.Path(__file__).resolve().parents[2]
FROM_S = 0
TO_S = 4102444800  # 2100-01-01T00:00:00Z
UTC = datetime.timezone.utc
NAIVE_EPOCH = datetime.datetime(1970, 1, 1)


def tzdir():
    for d in zoneinfo.TZPATH:
        if (pathlib.Path(d) / "+VERSION").is_file():
            return pathlib.Path(d)
    sys.exit("no tzdata directory with a +VERSION file on zoneinfo.TZPATH")


def calendars():
    with open(ROOT / "registries" / "calendars.toml", "rb") as f:
        return tomllib.load(f)["calendar"]


def offset_s(tz, t):
    off = datetime.datetime.fromtimestamp(t, tz).utcoffset().total_seconds()
    if off % 60:
        sys.exit(f"{tz.key}: offset {off} s at {t} is not a whole number of minutes")
    return int(off)


def transitions(tz):
    out, t, cur = [], FROM_S, offset_s(tz, FROM_S)
    while t < TO_S:
        nxt = min(t + 3600, TO_S - 1)
        if offset_s(tz, nxt) != cur:
            lo, hi = t, nxt  # offset(lo) == cur != offset(hi)
            while hi - lo > 1:
                mid = (lo + hi) // 2
                if offset_s(tz, mid) == cur:
                    lo = mid
                else:
                    hi = mid
            new = offset_s(tz, hi)
            if offset_s(tz, hi - 1) != cur or new == cur:
                sys.exit(f"{tz.key}: change near {hi} does not hold at its second")
            out.append((hi, new))
            cur = new
        t = nxt if nxt > t else TO_S
    return out


def registry():
    d = tzdir()
    version = (d / "+VERSION").read_text().strip()
    zones = sorted({c["tz_name"] for c in calendars()})
    w = sys.stdout.write
    w("# registries/zones.toml — UTC offsets of the IANA zones that registries/calendars.toml names (plan §25.4,\n")
    w("# BD-029). DST rules are data: an offset holds from its transition's UTC second up to the next one. The span\n")
    w("# is [from_utc_s, to_utc_s); fmine-time refuses any instant outside it.\n")
    w("# Generated by `python3 -I scripts/oracle/zone_snapshot.py registry` from CPython zoneinfo over the tzdata\n")
    w("# named below; tzif_sha256 is the TZif file read. Regenerate, never edit by hand.\n\n")
    w(f'schema_version = 1\ntzdata = "{version}"\nfrom_utc_s = {FROM_S}\nto_utc_s = {TO_S}\n')
    found = {}
    for name in zones:
        tz = zoneinfo.ZoneInfo(name)
        sha = hashlib.sha256((d / name).read_bytes()).hexdigest()
        found[name] = transitions(tz)
        w(f'\n[[zone]]\ntz_name = "{name}"\ntzif_sha256 = "{sha}"\noffset_minutes = {offset_s(tz, FROM_S) // 60}\n')
    for name in zones:
        for at, off in found[name]:
            w(f'\n[[transition]]\ntz_name = "{name}"\nat_utc_s = {at}\noffset_minutes = {off // 60}\n')


def to_utc_options(tz, local_s):
    naive = NAIVE_EPOCH + datetime.timedelta(seconds=local_s)
    hits = set()
    for fold in (0, 1):
        u = naive.replace(tzinfo=tz, fold=fold).astimezone(UTC)
        if u.astimezone(tz).replace(tzinfo=None) == naive:
            hits.add(int(u.timestamp()))
    return sorted(hits)


def local_kind(tz, local_s):
    hits = to_utc_options(tz, local_s)
    if not hits:
        return "gap"
    if len(hits) > 1:
        return "ambiguous"
    return f"unique {hits[0]}"


def oracle():
    w = sys.stdout.write
    cals = calendars()
    zones = sorted({c["tz_name"] for c in cals})
    trans = {}
    for name in zones:
        tz = zoneinfo.ZoneInfo(name)
        trans[name] = transitions(tz)
        for at, _ in trans[name]:
            for t in (at - 1, at):
                w(f"offset {name} {t} {offset_s(tz, t) // 60}\n")
        for at, new in trans[name]:
            old = offset_s(tz, at - 1)
            edges = (at + old, at + new) if new > old else (at + new, at + old)
            for local_s in (edges[0] - 1, edges[0], edges[1] - 1, edges[1]):
                w(f"local {name} {local_s} {local_kind(tz, local_s)}\n")
    for c in cals:
        tz = zoneinfo.ZoneInfo(c["tz_name"])
        days = set()
        for year in range(1970, 2100):
            days |= {datetime.date(year, 1, 15), datetime.date(year, 7, 15)}
        for at, _ in trans[c["tz_name"]]:
            days.add(datetime.datetime.fromtimestamp(at, tz).date())
        for day in sorted(days):
            local_s = (day - NAIVE_EPOCH.date()).days * 86400 + c["day_start_local_hour"] * 3600
            w(f"cut {c['site_id']} {day.isoformat()} {local_kind(tz, local_s).removeprefix('unique ')}\n")


if __name__ == "__main__":
    if len(sys.argv) != 2 or sys.argv[1] not in ("registry", "oracle"):
        sys.exit(__doc__)
    {"registry": registry, "oracle": oracle}[sys.argv[1]]()
